#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Tile {
    pub id: u8,
    pub name: &'static str,
    pub name_en: &'static str,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Npc {
    pub x: u8,
    pub y: u8,
    pub sprite: u8,
    pub direction: u8,
    pub moving: bool,
    pub talk_id: u8,
    pub dialogue_id: Option<u16>, // talk_id がメッセージ表示のときの DIALOGUE_MASTER の添字
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GameMap {
    pub id: u8,
    pub name: &'static str,
    pub name_en: &'static str,
    pub kind: &'static str, // "field" | "town" | "castle" | "shrine" | "dungeon"
    pub width: u8,
    pub height: u8,
    pub border_tile: u8,
    pub tiles: &'static [u8], // 行優先で平坦化 (index = y * width + x)
    pub npcs: &'static [Npc],
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Warp {
    pub from: (u8, u8, u8), // (map, x, y)
    pub to: (u8, u8, u8),
}

pub fn find_map(id: u8) -> Option<&'static GameMap> {
    MAP_MASTER.iter().find(|m| m.id == id)
}

