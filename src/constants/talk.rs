#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TalkKind {
    WeaponShop,
    ItemShop,
    KeyShop,
    FairyWaterShop,
    Inn,
    Message,
    Question,
    Event,
}

impl TalkKind {
    pub fn as_str(self) -> &'static str {
        match self {
            TalkKind::WeaponShop => "weapon_shop",
            TalkKind::ItemShop => "item_shop",
            TalkKind::KeyShop => "key_shop",
            TalkKind::FairyWaterShop => "fairy_water_shop",
            TalkKind::Inn => "inn",
            TalkKind::Message => "message",
            TalkKind::Question => "question",
            TalkKind::Event => "event",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShopItem {
    Weapon(u8), // WEAPON_MASTER の添字
    Armor(u8),  // ARMOR_MASTER の添字
    Shield(u8), // SHIELD_MASTER の添字
    Item(u8),   // ITEM_MASTER の添字
    Herb,       // やくそう
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ShopEntry {
    pub item: ShopItem,
    pub name: &'static str,
    pub price: u16,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Talk {
    pub talk_id: u8,
    pub kind: TalkKind,
    pub items: &'static [ShopEntry], // WeaponShop / ItemShop の品ぞろえ
    pub price: Option<u16>,          // KeyShop: かぎ 1 つ、FairyWaterShop: せいすい 1 つ、Inn: 1 泊
    pub dialogue_id: Option<u16>,    // Message / Question で最初に表示するセリフ
    pub yes_dialogue_id: Option<u16>, // Question で「はい」
    pub no_dialogue_id: Option<u16>, // Question で「いいえ」
    pub role: Option<&'static str>,  // Event の役割
    pub role_en: Option<&'static str>,
    pub related_dialogue_ids: &'static [u16], // 条件で差し替え・追加されるセリフ、お店やイベントで使うセリフ
}

pub fn find_talk(talk_id: u8) -> Option<&'static Talk> {
    TALK_MASTER.iter().find(|t| t.talk_id == talk_id)
}

