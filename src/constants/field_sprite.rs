// pixels はファミコンの色番号 (NES_PALETTE の添字)、TRANSPARENT は透明。

pub const TRANSPARENT: u8 = 0xFF;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PaletteSet {
    Field,   // マップ 1
    Town,    // マップ 2-14
    Dungeon, // マップ 15-
}

impl PaletteSet {
    pub fn of_map(map_id: u8) -> Self {
        match map_id {
            1 => PaletteSet::Field,
            2..=14 => PaletteSet::Town,
            _ => PaletteSet::Dungeon,
        }
    }

    pub fn index(self) -> usize {
        self as usize
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MapTileSprite {
    pub id: u8,                          // TILE_MASTER の id
    pub tiles: [u8; 4],                  // 左上・右上・左下・右下 (BG_TILE_PATTERNS のキー)
    pub palette: u8,                     // BG_PALETTES[PaletteSet] の添字
    pub pixels: [&'static [u8; 256]; 3], // PaletteSet ごとの 16x16、行優先
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CharacterPart {
    pub tile: u8, // SPRITE_TILE_PATTERNS のキー
    pub x: u8,
    pub y: u8,
    pub palette: u8, // SPRITE_PALETTE の添字
    pub flip_h: bool,
    pub flip_v: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CharacterFrame {
    pub parts: [CharacterPart; 4],
    pub pixels: &'static [u8; 256], // 16x16、行優先
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CharacterSprite {
    pub id: u8,
    pub name: &'static str,
    pub name_en: &'static str,
    pub frames: [CharacterFrame; 2], // 歩行アニメーション (向きはなく常に正面)
}

pub fn map_tile_sprite(tile_id: u8) -> Option<&'static MapTileSprite> {
    MAP_TILE_SPRITE_MASTER.get(tile_id as usize)
}

pub fn map_tile_pixels(tile_id: u8, map_id: u8) -> Option<&'static [u8; 256]> {
    map_tile_sprite(tile_id).map(|t| t.pixels[PaletteSet::of_map(map_id).index()])
}

// Npc::sprite と表示するマップから CHARACTER_SPRITE_MASTER の添字を求める
pub fn npc_character_id(sprite: u8, map_id: u8, after_ending: bool) -> u8 {
    match (sprite, map_id) {
        (6, 5) => 13,
        (6, 4) if after_ending => 13,
        (5, 6) => 14,
        (5, 4) if after_ending => 15,
        _ => sprite,
    }
}

pub fn hero_character_id(has_weapon: bool, has_shield: bool, with_princess: bool) -> u8 {
    if with_princess {
        12
    } else {
        8 + has_weapon as u8 + has_shield as u8 * 2
    }
}

pub fn pixel_rgb(color: u8) -> Option<(u8, u8, u8)> {
    (color != TRANSPARENT).then(|| NES_PALETTE[(color & 0x3F) as usize])
}

