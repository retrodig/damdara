// その場所で出る敵のグループ。None は敵が出ない (町・城・ほこら、ロトのどうくつ)
pub fn encounter_group(map_id: u8, x: u8, y: u8) -> Option<u8> {
    match map_id {
        1 => FIELD_ZONES
            .get((y / FIELD_ZONE_SIZE) as usize)
            .and_then(|row| row.get((x / FIELD_ZONE_SIZE) as usize))
            .copied(),
        2 => Some(16),
        3 => Some(13),
        6 => Some(18),
        15 => Some(16),
        16 => Some(17),
        17 => Some(17),
        18 => Some(17),
        19 => Some(18),
        20 => Some(18),
        21 => Some(19),
        22 => Some(19),
        23 => Some(14),
        24 => Some(14),
        25 => Some(7),
        26 => Some(15),
        27 => Some(15),
        _ => None,
    }
}

// 1 歩ごとの出現率 1/n (足元のタイルで決まる)
pub fn encounter_one_in(tile_id: u8, x: u8, y: u8) -> u8 {
    match tile_id {
        6 => 16,
        1 => 8,
        2 => 8,
        11 => 16,
        4 => 16,
        13 => 16,
        _ if (x as u16 + y as u16) % 2 == 0 => 32,
        _ => 16,
    }
}

// グループ 0 の区画では、出現が決まっても丘なら 3/4、それ以外は 1/2 の確率で取りやめる
pub fn group0_battle_chance(tile_id: u8) -> (u8, u8) {
    if tile_id == 2 { (1, 4) } else { (1, 2) }
}

// せいすい の効果中は弱い敵が出ない。true なら戦闘にならない (フィールドのみ)
pub fn repelled_by_fairy_water(monster_attack: u8, player_defense: u8) -> bool {
    let diff = monster_attack as i16 - (player_defense / 2) as i16;
    diff < 0 || (monster_attack / 2) as i16 >= diff
}
